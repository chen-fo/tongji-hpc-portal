import { test, expect } from '@playwright/test';

test('administrator configures three accounts and provisions independent Alice/Bob identities', async ({ page, browser }) => {
  const password = process.env.PORTAL_E2E_PASSWORD!;
  await page.goto('/');
  await page.getByLabel('用户名', { exact: true }).fill('admin');
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '登 录' }).click();
  await expect(page.getByRole('heading', { name: '你好，admin' })).toBeVisible();
  await page.getByRole('menuitem', { name: '官方账号' }).click();
  for (const letter of ['a', 'b', 'c']) {
    await page.getByRole('button', { name: '添加官方账号' }).click();
    await page.getByLabel('内部别名').fill(`official_${letter}`);
    await page.getByLabel('SSH 主机').fill(`mock-${letter}`);
    await page.getByLabel('SSH 用户名').fill(`research_${letter}`);
    await page.getByLabel('密钥引用').fill('mock-key');
    await page.getByRole('button', { name: '保存账号' }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
  }
  await expect(page.getByRole('button', { name: '添加官方账号' })).toBeDisabled();
  await page.getByRole('button', { name: '编 辑' }).first().click();
  await page.getByLabel('密钥引用').fill('rotated-mock-key');
  await page.getByRole('button', { name: '保存账号' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('rotated-mock-key')).toBeVisible();
  await page.getByRole('button', { name: '检查连接' }).first().click();
  await expect(page.getByText('Mock 连接成功 · /mock-cluster/home/research_a')).toBeVisible();
  await page.getByRole('menuitem', { name: '组内用户' }).click();
  for (const name of ['alice', 'bob']) {
    await page.getByRole('button', { name: '创建用户' }).click();
    await page.getByLabel('用户名', { exact: true }).fill(name);
    await page.getByLabel('初始密码').fill(password);
    await page.getByRole('combobox').click();
    await page.getByText('official_a', { exact: true }).last().click();
    await page.getByRole('button', { name: '创建并准备目录' }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await expect(page.getByText(`/mock-cluster/home/research_a/user/${name}`)).toBeVisible();
  }
  await page.screenshot({ path: 'test-results/users.png', fullPage: true });
  const context = await browser.newContext();
  const student = await context.newPage();
  await student.goto('/');
  await student.getByLabel('用户名', { exact: true }).fill('alice');
  await student.getByLabel('密码', { exact: true }).fill(password);
  await student.getByRole('button', { name: '登 录' }).click();
  await expect(student.getByRole('heading', { name: '你好，alice' })).toBeVisible();
  await expect(student.getByRole('menuitem', { name: '组内用户' })).toHaveCount(0);
  await expect(student.getByText('/mock-cluster/home/research_a/user/alice')).toBeVisible();
  expect((await context.request.get('/api/admin/users')).status()).toBe(403);
  await student.reload();
  await expect(student.getByRole('heading', { name: '你好，alice' })).toBeVisible();
  await student.getByRole('menuitem', { name: '终端' }).click();
  await student.getByRole('button', { name: '连接终端' }).click();
  await expect(student.getByText('已连接', { exact: true })).toBeVisible();
  await student.locator('.xterm-helper-textarea').focus();
  await student.keyboard.type('pwd');
  await student.keyboard.press('Enter');
  await student.keyboard.type('cd /tmp');
  await student.keyboard.press('Enter');
  await student.keyboard.type('pwd');
  await student.keyboard.press('Enter');
  await student.keyboard.type('cd ~');
  await student.keyboard.press('Enter');
  await student.keyboard.type('pwd');
  await student.keyboard.press('Enter');
  await expect.poll(async () => {
    const response = await page.request.get('/api/admin/audit?username=alice');
    return (await response.json()).total;
  }).toBe(5);
  await page.getByRole('menuitem', { name: '命令记录' }).click();
  await expect(page.getByRole('cell', { name: 'cd /tmp', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: '/tmp', exact: true }).first()).toBeVisible();
  await student.screenshot({ path: 'test-results/terminal.png', fullPage: true });
  await page.getByRole('menuitem', { name: '组内用户' }).click();
  const aliceRow = page.getByRole('row').filter({ hasText: 'alice' });
  await aliceRow.getByRole('button', { name: '停用 / 归档' }).click();
  await page.getByRole('button', { name: '确 认' }).click();
  await expect(aliceRow.getByText('已归档')).toBeVisible();
  await expect(student.getByText('已断开', { exact: true })).toBeVisible();
  await student.reload();
  await expect(student.getByText('登录 Portal')).toBeVisible();
  await aliceRow.getByRole('button', { name: '启 用' }).click();
  await page.getByRole('button', { name: '确 认' }).click();
  await expect(aliceRow.getByText('已归档')).toHaveCount(0);
  await aliceRow.getByRole('button', { name: '重置密码' }).click();
  const resetPassword = password + '-reset';
  await page.getByLabel('新密码', { exact: true }).fill(resetPassword);
  await page.getByRole('button', { name: '重置密码并撤销会话' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await student.getByLabel('用户名', { exact: true }).fill('alice');
  await student.getByLabel('密码', { exact: true }).fill(resetPassword);
  await student.getByRole('button', { name: '登 录' }).click();
  await expect(student.getByRole('heading', { name: '你好，alice' })).toBeVisible();
  await student.getByRole('menuitem', { name: '设置' }).click();
  await student.getByLabel('当前密码').fill(resetPassword);
  await student.getByLabel('新密码', { exact: true }).fill(password + '-changed');
  await student.getByLabel('确认新密码').fill(password + '-changed');
  await student.getByRole('button', { name: '保存新密码' }).click();
  await expect(student.getByText('登录 Portal')).toBeVisible();
  await student.getByLabel('用户名', { exact: true }).fill('alice');
  await student.getByLabel('密码', { exact: true }).fill(password + '-changed');
  await student.getByRole('button', { name: '登 录' }).click();
  await expect(student.getByRole('heading', { name: '你好，alice' })).toBeVisible();
  await context.close();
  await page.getByRole('button', { name: '退出登录' }).click();
  await expect(page.getByText('登录 Portal')).toBeVisible();
});
